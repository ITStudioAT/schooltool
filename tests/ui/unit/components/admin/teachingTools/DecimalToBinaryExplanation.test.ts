import { afterEach, expect, it, vi } from 'vitest'
import { mount } from '@vue/test-utils'
import DecimalToBinaryExplanation from '@/pages/admin/teachingTools/DecimalToBinaryExplanation.vue'

const wrappers: ReturnType<typeof mount>[] = []
function render() { const wrapper = mount(DecimalToBinaryExplanation); wrappers.push(wrapper); return wrapper }
function button(wrapper, name) { return wrapper.findAll('button').find(item => item.text().includes(name))! }
afterEach(() => { wrappers.splice(0).forEach(wrapper => wrapper.unmount()); vi.useRealTimers() })

async function advanceUntil(wrapper, selector) {
    for (let count = 0; count < 100 && !wrapper.find(selector).exists(); count++) {
        await button(wrapper, 'Weiter').trigger('click')
    }
    expect(wrapper.find(selector).exists()).toBe(true)
}

async function advanceToInstruction(wrapper, title) {
    for (let count = 0; count < 100 && wrapper.find('[data-testid="step-instruction"] h2').text() !== title; count++) {
        await button(wrapper, 'Weiter').trigger('click')
    }
    expect(wrapper.get('[data-testid="step-instruction"] h2').text()).toBe(title)
}

