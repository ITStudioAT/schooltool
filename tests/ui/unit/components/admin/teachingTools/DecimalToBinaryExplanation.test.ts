it('divides 13 and reads the remainders in reverse before showing its place-value proof', async () => {
    const wrapper = render()
    await advanceUntil(wrapper, '#binary-phase-title')
    expect(wrapper.findAll('.binary-row').map(row => row.text().replace(/\s/g, ''))).toEqual(['13÷2=61', '6÷2=30', '3÷2=11', '1÷2=01'])
    expect(wrapper.get('[role="status"]').text()).toContain('Das Teilen ist fertig!')
    expect(wrapper.findAll('.binary-digit--known')).toHaveLength(0)
    await button(wrapper, 'Weiter').trigger('click')
    expect(wrapper.get('[data-testid="step-instruction"]').text()).toBe('Reste von unten nach oben lesen.')
    expect(wrapper.get('[data-testid="step-instruction"]').find('ul').exists()).toBe(false)
    expect(wrapper.findAll('.binary-digit--known')).toHaveLength(0)
    await button(wrapper, 'Weiter').trigger('click')
    expect(wrapper.findAll('.binary-digit--known').map(item => item.get('strong').text())).toEqual(['1'])
    expect(wrapper.get('[data-testid="step-instruction"]').text()).toContain('Beginne ganz unten')
    expect(wrapper.get('.binary-reading-hint--active').text()).toContain('von unten nach oben')
    expect(wrapper.findAll('.binary-rest-arrow--current')).toHaveLength(1)
    expect(wrapper.findAll('.binary-row').at(-1)?.find('.binary-rest-arrow--current').exists()).toBe(true)
    await advanceUntil(wrapper, '[aria-label="Probe mit Stellenwerten"]')
    expect(wrapper.get('[data-testid="binary-result"]').text()).toBe('13 = 11012')
    expect(wrapper.get('[data-testid="binary-result"]').findAll('sub').map(item => item.text())).toEqual(['2'])
    expect(wrapper.get('[aria-label="Probe mit Stellenwerten"]').text()).toContain('8 + 4 + 1 = 13')
    expect(button(wrapper, 'Weiter').attributes('disabled')).toBeDefined()
    expect(wrapper.get('.binary-completion').text()).toContain('Erklärung abgeschlossen.')
    expect(wrapper.get('.binary-completion').text()).toContain('Oben kannst du eine andere Zahl eingeben.')
    expect(wrapper.get('.binary-completion').element.previousElementSibling).toBe(wrapper.get('.binary-controls').element)
    await button(wrapper, 'Zurück').trigger('click')
    expect(wrapper.find('.binary-completion').exists()).toBe(false)
    expect(wrapper.find('[aria-label="Probe mit Stellenwerten"]').exists()).toBe(false)
    await button(wrapper, 'Neu starten').trigger('click')
    expect(wrapper.findAll('.binary-row')).toHaveLength(1)
    expect(wrapper.get('.binary-remainder').text()).toBe('?')
    expect(wrapper.findAll('.binary-digit--known')).toHaveLength(0)
    expect(wrapper.find('.binary-completion').exists()).toBe(false)
    expect(button(wrapper, 'Weiter').attributes('disabled')).toBeUndefined()
})

it.each([0, 65535])('accepts a new number and completes %s while leaving the example unchanged on invalid input', async number => {
    const wrapper = render()
    await wrapper.get('input').setValue('25')
    await wrapper.get('form').trigger('submit')
    expect(wrapper.get('[data-testid="step-instruction"]').text()).toContain('25')
    await wrapper.get('input').setValue('2.5')
    await wrapper.get('form').trigger('submit')
    expect(wrapper.get('[role="alert"]').text()).toContain('ganze Zahl')
    expect(wrapper.get('[data-testid="step-instruction"]').text()).toContain('25')
    await wrapper.get('input').setValue(String(number))
    await wrapper.get('form').trigger('submit')
    await advanceUntil(wrapper, '[aria-label="Probe mit Stellenwerten"]')
    expect(wrapper.get('[data-testid="binary-result"]').text()).toBe(`${number} = ${number.toString(2)}2`)
    expect(wrapper.get('[aria-label="Probe mit Stellenwerten"]').text()).toContain(`= ${number}`)
    expect(wrapper.get('.binary-completion').text()).toContain('Erklärung abgeschlossen.')
    await wrapper.get('input').setValue('25')
    await wrapper.get('form').trigger('submit')
    expect(wrapper.find('.binary-completion').exists()).toBe(false)
    expect(wrapper.get('[data-testid="step-instruction"]').text()).toBe('Wir teilen 25 durch 2.')
    expect(button(wrapper, 'Weiter').attributes('disabled')).toBeUndefined()
})

it('advances only manually, allows returning to earlier explanations and has no playback or speed control', async () => {
    vi.useFakeTimers()
    const wrapper = render()
    expect(wrapper.findAll('button').map(item => item.text())).toEqual(['Zahl übernehmen', '← Zurück', 'Weiter →', 'Neu starten'])
    expect(wrapper.find('select').exists()).toBe(false)
    const initialInstruction = wrapper.get('[data-testid="step-instruction"]').text()
    await vi.advanceTimersByTimeAsync(60000)
    expect(wrapper.get('[data-testid="step-instruction"]').text()).toBe(initialInstruction)

    await advanceToInstruction(wrapper, '13 ÷ 2 = 6, Rest 1')
    const remainderInstruction = wrapper.get('[data-testid="step-instruction"]').text()
    await vi.advanceTimersByTimeAsync(60000)
    expect(wrapper.get('[data-testid="step-instruction"]').text()).toBe(remainderInstruction)
    await advanceToInstruction(wrapper, 'Wir teilen 6 durch 2.')
    expect(wrapper.findAll('.binary-row')).toHaveLength(2)
    expect(wrapper.get('[data-testid="step-instruction"]').text()).toContain('Quotienten 6')
    for (let step = 0; step < 6; step++) await button(wrapper, 'Zurück').trigger('click')
    expect(wrapper.get('[data-testid="step-instruction"]').text()).toBe(remainderInstruction)
    for (let step = 0; step < 8; step++) await button(wrapper, 'Zurück').trigger('click')
    expect(wrapper.get('[data-testid="step-instruction"]').text()).toBe(initialInstruction)
    expect(wrapper.get('.binary-remainder').text()).toBe('?')
})

it('waits at the phase change for the same Next control and returns there with Back', async () => {
    vi.useFakeTimers()
    const wrapper = render()
    const nextControl = button(wrapper, 'Weiter').element
    await advanceUntil(wrapper, '#binary-phase-title')

    expect(wrapper.get('#binary-phase-title').text()).toBe('Das Teilen ist fertig!')
    expect(button(wrapper, 'Weiter').element).toBe(nextControl)
    expect(wrapper.get('.binary-phase-stop').find('button').exists()).toBe(false)
    expect(wrapper.findAll('button').filter(item => item.text().includes('Weiter'))).toHaveLength(1)
    expect(wrapper.findAll('.binary-digit--known')).toHaveLength(0)
    expect(wrapper.find('.binary-reading-hint--active').exists()).toBe(false)
    await vi.advanceTimersByTimeAsync(60000)
    expect(wrapper.find('#binary-phase-title').exists()).toBe(true)
    expect(wrapper.findAll('.binary-digit--known')).toHaveLength(0)

    await button(wrapper, 'Weiter').trigger('click')
    expect(wrapper.find('#binary-phase-title').exists()).toBe(false)
    expect(wrapper.find('.binary-result').exists()).toBe(true)
    expect(wrapper.findAll('.binary-digit--known')).toHaveLength(0)
    await button(wrapper, 'Zurück').trigger('click')
    expect(wrapper.find('#binary-phase-title').exists()).toBe(true)
    expect(wrapper.findAll('.binary-digit--known')).toHaveLength(0)
})
