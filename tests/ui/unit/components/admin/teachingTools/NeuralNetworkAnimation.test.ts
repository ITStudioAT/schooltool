import { Window } from 'happy-dom'
import { describe, expect, it } from 'vitest'
import animationDocument from '@/pages/admin/teachingTools/NeuralNetworkAnimation.html?raw'

describe('Neural network learning animation', () => {
    it('explains the example step by step and allows restarting', () => {
        const window = new Window({ url: 'http://localhost/', settings: { enableJavaScriptEvaluation: true } })
        window.document.write(animationDocument)
        const page = window.document
        const next = page.getElementById('next')
        const back = page.getElementById('back')

        expect([...page.querySelectorAll('button')].map(button => button.textContent)).toEqual(['Zurück', 'Weiter', 'Neustart'])
        expect(back.disabled).toBe(true)
        expect(page.getElementById('stage-title').textContent).toBe('Die Katze')

        next.click()
        expect(page.getElementById('stage-title').textContent).toBe('Die Merkmale')
        next.click()
        expect(page.getElementById('stage-title').textContent).toBe('Alle inneren Neuronen rechnen')
        expect(page.querySelectorAll('.node.hidden')).toHaveLength(4)
        expect(page.getElementById('input-calculation').hidden).toBe(false)
        expect(page.getElementById('input-calculation-example').textContent).toContain('0,90 × 0,32 ≈ 0,288')
        expect(page.getElementById('input-calculation-example').textContent).toContain('0,20 × -0,24 ≈ -0,048')
        expect(page.getElementById('input-calculation-example').textContent).toContain('0,288 + (-0,048) + (0,030) ≈ 0,270')
        expect(page.getElementById('input-calculation-example').textContent).toContain('0,270 ≈ 0,27')
        expect(page.getElementById('input-calculation').textContent).toContain('Gewicht E1:')
        expect(page.getElementById('input-calculation').textContent).toContain('Gewicht E2:')
        expect(page.getElementById('input-calculation').textContent).toContain('Grundwert:')
        expect(page.getElementById('input-calculation').textContent.toLowerCase()).not.toContain('tanh')
        expect(page.querySelectorAll('#input-calculation .calculation-example')).toHaveLength(4)
        expect(page.getElementById('input-calculation-values').textContent).toContain('Neuron N4')
        expect(page.getElementById('weight-example').hidden).toBe(true)

        next.click()
        expect(page.getElementById('facts').textContent).toContain('Hund')
        expect(page.getElementById('input-calculation').hidden).toBe(true)
        expect(page.getElementById('calculation').hidden).toBe(false)
        expect(page.getElementById('calculation-example').textContent).toContain('0,27 × -0,20 ≈ -0,05')
        expect(page.getElementById('calculation-values').textContent).toContain('-0,254')
        expect(page.getElementById('calculation-values').textContent).toContain('(-0,054) + (-0,042) + (-0,039) + (-0,069) + (-0,050) ≈ -0,254')
        expect(page.getElementById('calculation-percentages').textContent).toContain('Positive Zahlen berechnen')
        expect(page.getElementById('calculation-percentages').textContent).toContain('Beide Zahlen addieren')
        expect(page.getElementById('calculation-percentages').textContent).toContain('Den Anteil jeder Zahl berechnen')
        expect(page.getElementById('calculation-percentages').textContent).toContain('Die Anteile in Prozent umrechnen')
        expect(page.getElementById('calculation-percentages').textContent).toContain('38 %')
        expect(page.getElementById('calculation-percentages').textContent).toContain('62 %')
        next.click()
        expect(page.getElementById('stage-text').textContent).toContain('Hund')
        expect(page.getElementById('stage-text').textContent).toContain('Katze')
        next.click()
        expect(page.getElementById('stage-title').textContent).toBe('Die Rückmeldung läuft zurück')
        expect(page.querySelectorAll('.edge.feedback')).toHaveLength(16)
        next.click()
        expect(page.getElementById('stage-title').textContent).toBe('Die Verbindungen ändern sich')
        expect(page.querySelectorAll('.edge.updated')).toHaveLength(16)
        expect(page.getElementById('weights').textContent).toContain('0,2474 × 0,70 ≈ 0,1732')
        expect(page.getElementById('weights').textContent).toContain('0,320 − (0,1732) ≈ 0,147 ≈ 0,15')
        expect(page.getElementById('weights').textContent).toContain('0,2749 × 0,90 ≈ 0,2474')
        expect(page.querySelectorAll('#weight-changes tbody tr')).toHaveLength(22)
        expect(page.getElementById('weight-changes').textContent).toContain('E1 → N1')
        expect(page.getElementById('weight-changes').textContent).toContain('N4 → Hund')
        expect(page.getElementById('weight-example').hidden).toBe(false)
        next.click()
        expect(page.getElementById('stage-title').textContent).toBe('Die Katze noch einmal')
        expect(page.getElementById('facts').textContent).toContain('38 % → 71 %')

        for (let index = 0; index < 7; index++) next.click()
        expect(page.getElementById('stage-title').textContent).toBe('Der Hund noch einmal')
        expect(page.getElementById('facts').textContent).toContain('25 % → 59 %')
        next.click()
        expect(page.getElementById('stage-title').textContent).toBe('Beide Beispiele ansehen')
        expect(page.getElementById('results-slide').hidden).toBe(true)
        expect(page.getElementById('round-label').textContent).toContain('keine zusätzlichen Runden')
        const beforePractice = [...page.getElementById('facts').textContent.matchAll(/(\d+) %/g)].map(match => Number(match[1]))
        for (let index = 0; index < 4; index++) next.click()
        expect(page.getElementById('step').textContent).toBe('Schritt 20 von 21')
        const afterPractice = [...page.getElementById('facts').textContent.matchAll(/(\d+) %/g)].map(match => Number(match[1]))
        expect(afterPractice[0]).toBeGreaterThan(beforePractice[0])
        expect(afterPractice[1]).toBeGreaterThan(beforePractice[1])
        expect(page.getElementById('round-label').textContent).toBe('Nach 12 zusätzlichen Lernrunden')
        expect(page.getElementById('results-slide').hidden).toBe(true)
        expect(page.querySelector('.svg-wrap').hidden).toBe(false)
        next.click()
        expect(page.getElementById('step').textContent).toBe('Schritt 21 von 21')
        expect(page.getElementById('results-slide').hidden).toBe(false)
        expect(page.querySelector('.svg-wrap').hidden).toBe(true)
        expect(page.getElementById('results-slide').textContent).toContain('Ergebnis nach 12 zusätzlichen Lernrunden')
        expect([...page.querySelectorAll('.future-results tbody tr')].slice(-2).map(row => row.textContent)).toEqual(['5099,77 %99,78 %', '10099,91 %99,91 %'])
        expect(next.disabled).toBe(true)

        back.click()
        expect(page.getElementById('stage-title').textContent).toBe('Weiterlernen: 12 Runden')
        expect(page.getElementById('results-slide').hidden).toBe(true)
        expect(page.querySelector('.svg-wrap').hidden).toBe(false)
        expect(page.getElementById('weight-example').hidden).toBe(true)
        expect(next.disabled).toBe(false)
        page.getElementById('restart').click()
        expect(page.getElementById('step').textContent).toBe('Schritt 1 von 21')
        expect(page.getElementById('stage-title').textContent).toBe('Die Katze')
        expect(page.getElementById('results-slide').hidden).toBe(true)
        window.close()
    })

    it('restores a valid step from its parent and ignores invalid messages', () => {
        const window = new Window({ url: 'http://localhost/', settings: { enableJavaScriptEvaluation: true } })
        window.document.write(animationDocument)
        const page = window.document

        const parentWindow = window.eval('window.parent')
        window.dispatchEvent(new window.MessageEvent('message', { source: parentWindow, data: { type: 'schooltool-neural-network-show-step', step: 8 } }))
        expect(page.getElementById('step').textContent).toBe('Schritt 8 von 21')
        expect(page.getElementById('stage-title').textContent).toBe('Die Katze noch einmal')
        expect(page.getElementById('facts').textContent).toContain('38 % → 71 %')

        window.dispatchEvent(new window.MessageEvent('message', { source: parentWindow, data: { type: 'schooltool-neural-network-show-step', step: 22 } }))
        window.dispatchEvent(new window.MessageEvent('message', { data: { type: 'schooltool-neural-network-show-step', step: 2 } }))
        expect(page.getElementById('step').textContent).toBe('Schritt 8 von 21')
        window.close()
    })
})
